#!/usr/bin/env python3

    # 1. กำหนดอาเรย์ (list) เริ่มต้นตามโจทย์
original_array = [2, 8, 9, 48, 8, 22, -12, 2]
    
# 2. สร้างอาเรย์ใหม่โดยเลือกเฉพาะค่าที่มากกว่า 5 และทำการบวกเพิ่มเข้าไป (เช่น บวก 2 ในแต่ละตัว)
    # หมายเหตุ: รูปแบบนี้เรียกว่า List Comprehension
modified_array = [x + 2 for x in original_array if x > 5]
    
    # 3. แสดงผลลัพธ์อาเรย์เดิมออกทางหน้าจอ
print(original_array)
    
    # 4. แสดงผลลัพธ์อาเรย์ใหม่ที่ผ่านการกรองและประมวลผลแล้วออกทางหน้าจอ
print(modified_array)



